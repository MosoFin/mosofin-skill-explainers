    path = f"skills/{r['skill']}/{kind}.html"
    title = html.unescape(re.search(r"<title>(.*?)</title>", text, re.S).group(1).strip())
    desc = html.unescape(re.search(r'<meta name="description" content="(.*?)"', text, re.S).group(1).strip())
    h1 = html.unescape(re.sub(r"<[^>]+>", "", re.search(r"<h1[^>]*>(.*?)</h1>", text, re.S).group(1))).strip()
    text = re.sub(re.escape(SEO_START) + r".*?" + re.escape(SEO_END) + r"\n?", "", text, flags=re.S)
    if "</head>" not in text:
        text = text.replace('<div class="wrap"', '</head>\n<body>\n<div class="wrap"', 1)
    if "</body>" not in text:
        text = text.rstrip("\n") + "\n</body>\n</html>\n"
    text = text.replace('<div class="wrap">', '<div class="wrap" role="main">', 1)
    label = next(l for k2, l, *_ in KINDS if k2 == kind)
    crumbs = [(f"{BRAND} skill explainers", SITE_URL), (title_of(r), f"{SITE_URL}skills/{r['skill']}/"), (label, SITE_URL + path)]
    block = seo_block(path, title, desc, "page", r["verified"], crumbs, about=skill_source(r), headline=h1)
    text = re.sub(r'(<meta name="description" content=".*?">\n)', lambda m: m.group(1) + block + "\n", text, count=1, flags=re.S)
    text = re.sub(re.escape(CITE_START) + r".*?" + re.escape(CITE_END) + r"\n?", "", text, flags=re.S)
    if kind in CITED:
        text = text.replace("</body>", cite_block(r["verified"]) + "</body>", 1)
    return text


