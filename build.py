def chip(r, k):
    st = r[k]
    if st == "todo": return '<td class="c"><span class="dash">—</span></td>'
    if st == "internal": return '<td class="c"><span class="dash">—</span></td>'
    return f'<td class="c"><a href="skills/{e(r["skill"])}/{k}.html"><span class="pill ok">view</span></a></td>'

# A kind gets a column on the public index once some skill has a published page of
# that kind, so a kind that is only ever internal never shows up as a gap.
def shown_kinds(rows):
    return [K for K in KINDS if any(r[K[0]] == "published" for r in rows)]

WAYS = {"plain": "in plain words for business owners",
        "learn": "step by step with worked examples and cited sources",
        "anatomy": "how it is built"}

def index(rows):
    n = len(rows)
    kinds = shown_kinds(rows)
    ways = [WAYS[k] for k, *_ in kinds]
    ways = ways[0] if len(ways) == 1 else ", ".join(ways[:-1]) + " and " + ways[-1]
    count = {1: "one way", 2: "two ways", 3: "three ways"}.get(len(kinds), f"{len(kinds)} ways")
    with_any = [r for r in rows if published_kinds(r)]   # a skill whose pages are all internal gets no public page or link
    pages = sum(1 for r in rows for k, *_ in KINDS if r[k] == "published")
    trs = []
    for r in rows:
        name = (f'<a href="skills/{e(r["skill"])}/">{e(title_of(r))}</a>' if r in with_any else e(title_of(r)))
        trs.append(f'<tr><td>{name}<br><code style="font-size:12px;color:var(--faint)">{e(r["skill"])}</code></td>'
                   f'<td>{e(r["genre"])}</td>' + "".join(chip(r, k) for k, *_ in kinds) + "</tr>")
    body = f"""<header>
  <span class="label">MosoFin finance skills</span>
  <h1>Skill explainers</h1>
  <p class="lede">Each finance skill, explained {count}: {ways}. Generated from <code>tracker.tsv</code>.</p>
</header>
<section>
  <div class="stats">
    <div class="stat"><span class="label">Skills tracked</span><span class="v">{n}</span><span class="s">in the tracker</span></div>
    <div class="stat"><span class="label">With explainers</span><span class="v">{len(with_any)}</span><span class="s">at least one page</span></div>
    <div class="stat"><span class="label">Pages</span><span class="v">{pages}</span><span class="s">published, of {n * len(kinds)} possible</span></div>
  </div>
</section>
<section>
  <h2>All skills</h2>
  <div class="tbl"><table>
    <thead><tr><th>Skill</th><th>Genre</th>{"".join(f'<th class="c">{e(l)}</th>' for _, l, *__ in kinds)}</tr></thead>
    <tbody>{"".join(trs)}</tbody>
  </table></div>
</section>
<footer>The skills themselves live in <a href="{SKILLS_REPO}">MosoFin/mosofin-finance-skills</a>. Explainers live here, separately, so nothing on this site is installed with a skill.</footer>"""
    names = [title_of(r).lower() for r in rows if published_kinds(r)]
    head = "Plain-English guides and worked examples for MosoFin's read-only finance skills: "
    natural = lambda xs: ", ".join(xs[:-1]) + (" and " if len(xs) > 1 else "") + xs[-1]
    desc = head + natural(names) + "." if names else head.rstrip(": ") + "."
    if len(desc) > DESC_MAX:  # too many skills to name: list as many as fit, then "and more"
        shown = []
        for nm in names:
            if len(head + ", ".join(shown + [nm]) + " and more.") > DESC_MAX: break
            shown.append(nm)
        desc = head + ", ".join(shown) + " and more."
    title = f"{BRAND} Skill Explainers: Plain-English Finance Guides"
    items = [(title_of(r), f"{SITE_URL}skills/{r['skill']}/") for r in rows if published_kinds(r)]
    return shell(title, body, desc, seo_block("", title, desc, "home", max((r["verified"] for r in rows if published_kinds(r)), default=""), items=items))

def sitemap(rows):
    urls = [(SITE_URL, max((r["verified"] for r in rows if published_kinds(r)), default=""))]
    for r in rows:
        ks = published_kinds(r)
        if not ks: continue
        urls.append((f"{SITE_URL}skills/{r['skill']}/", r["verified"]))
        urls += [(f"{SITE_URL}skills/{r['skill']}/{k}.html", r["verified"]) for k in ks]
    body = "".join(f"  <url>\n    <loc>{e(u)}</loc>\n" + (f"    <lastmod>{e(d)}</lastmod>\n" if d else "") + "  </url>\n" for u, d in urls)
    return ('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + body + "</urlset>\n")

def outputs(rows):
    out = {os.path.join(SITE, "index.html"): index(rows)}
    for r in rows:
        if published_kinds(r):
            out[os.path.join(SITE, "skills", r["skill"], "index.html")] = landing(r)
        for k in published_kinds(r):
            p = os.path.join(SITE, "skills", r["skill"], f"{k}.html")
            out[p] = seo_page(r, k, open(p).read())
        for k in CITED:   # internal plain/learn pages get the citation block too, so they read the same before they go public
            p = os.path.join(SITE, "skills", r["skill"], f"{k}.html")
            if r[k] == "internal" and os.path.exists(p):
                t = re.sub(re.escape(CITE_START) + r".*?" + re.escape(CITE_END) + r"\n?", "", open(p).read(), flags=re.S)
                out[p] = t.replace("</body>", cite_block(r["verified"]) + "</body>", 1)
    out[os.path.join(SITE, "sitemap.xml")] = sitemap(rows)
    return out

# Voice. Public explainers are written for people, so the habits that make prose read as machine-made fail the build.
BANNED = ["delv", "leverag", "utilis", "utiliz", "robust", "seamless", "streamlin", "empower", "foster", "pivotal",
          "game.?changer", "paradigm", "cutting.edge", "tapestr", "ever.evolving", "supercharg"]

def voice_problems(outs):
    """Em dashes and filler words in the prose of public pages. Quoted skill rules and empty-cell markers are exempt."""
    bad = []
    for p, h in sorted(outs.items()):
        rel = os.path.relpath(p, SITE)
        if not re.match(r"skills/[^/]+/(plain|learn)\.html$", rel): continue
        t = re.sub(r'<script type="application/ld\+json">.*?</script>|<style>.*?</style>|<!-- seo:start.*?seo:end -->|<blockquote>.*?</blockquote>', "", h, flags=re.S)
        t = re.sub(r'\bq:"(?:[^"\\]|\\.)*"', 'q:""', t)
        n = len(re.findall(r" — ", t))
        if n: bad.append(f"{rel}: {n} em dash(es) in prose. Use a comma, colon, brackets or a full stop; quoted skill rules are exempt")
        words = [w for w in BANNED if re.search(r"\b" + w + r"\w*", re.sub(r"<[^>]+>", " ", t), re.I)]
        if words: bad.append(f"{rel}: filler words {', '.join(words)}")
    return bad

def seo_problems(outs):
    """Search-facing checks on every page that will be published."""
    bad, titles, descs = [], {}, {}
    for p, h in sorted(outs.items()):
        if not p.endswith(".html"): continue
        rel = os.path.relpath(p, SITE)
        t = re.search(r"<title>(.*?)</title>", h, re.S); d = re.search(r'<meta name="description" content="(.*?)"', h, re.S)
        t = html.unescape(t.group(1).strip()) if t else ""; d = html.unescape(d.group(1).strip()) if d else ""
        if not TITLE_MIN <= len(t) <= TITLE_MAX: bad.append(f"{rel}: title is {len(t)} characters, want {TITLE_MIN}-{TITLE_MAX}")
        if not d: bad.append(f"{rel}: no meta description")
        elif not DESC_MIN <= len(d) <= DESC_MAX: bad.append(f"{rel}: description is {len(d)} characters, want {DESC_MIN}-{DESC_MAX}")
        if t in titles: bad.append(f"{rel}: same title as {titles[t]}")
        if d and d in descs: bad.append(f"{rel}: same description as {descs[d]}")
        titles.setdefault(t, rel); descs.setdefault(d, rel)
        if len(re.findall(r"<h1[\s>]", h)) != 1: bad.append(f"{rel}: needs exactly one <h1>")
        levels = [int(x) for x in re.findall(r"<h([1-6])[\s>]", h)]
        for a, b in zip(levels, levels[1:]):
            if b > a + 1: bad.append(f"{rel}: heading jumps from h{a} to h{b}"); break
        if SEO_START not in h: continue   # an internal plain/learn page: title, description and headings are checked, the SEO block comes when it is published
        cano = re.search(r'<link rel="canonical" href="(.*?)"', h)
        want = SITE_URL + rel.replace("index.html", "")
        if not cano or html.unescape(cano.group(1)) != want: bad.append(f"{rel}: canonical should be {want}")
        for blk in re.findall(r'<script type="application/ld\+json">(.*?)</script>', h, re.S):
            try: json.loads(blk)
            except ValueError as ex: bad.append(f"{rel}: JSON-LD does not parse ({ex})")
        if "<body" not in h or "</html>" not in h: bad.append(f"{rel}: missing <body> or </html>")
    return bad


# --------------------------------------------------------------------------- sync
def frontmatter_summary(path):
    t = open(path).read()
    m = re.search(r'^description:\s*"?(.*?)"?\s*$', t, re.M)
    d = re.sub(r"\s+", " ", m.group(1)) if m else ""
    first = re.split(r"(?<=[.!?])\s", d, maxsplit=1)[0]
    return first[:240]

def sync(path, ref):
    rows = {r["skill"]: r for r in read_tracker()}
    added = 0
    for genre, folder in [("analysis", "skills"), ("dashboard", "dashboards")]:
        base = os.path.join(path, folder)
        if not os.path.isdir(base): continue
        for s in sorted(os.listdir(base)):
            sk = os.path.join(base, s, "SKILL.md")
            if not os.path.exists(sk): continue
            shipped = subprocess.run(["git", "-C", path, "cat-file", "-e", f"{ref}:{folder}/{s}/SKILL.md"],
                                     capture_output=True).returncode == 0
            r = rows.get(s) or {c: "" for c in COLUMNS}
            if s not in rows:
                r.update(skill=s, genre=genre, plain="todo", learn="todo", anatomy="todo"); added += 1
            r["skill_status"] = "shipped" if shipped else "prototype"
            if not r["summary"]: r["summary"] = frontmatter_summary(sk)
            rows[s] = r
    write_tracker(list(rows.values()))
    print(f"sync: {added} added, {len(rows)} tracked")


# --------------------------------------------------------------------------- stage
def stage(dest):
    import shutil
    rows = read_tracker()
    internal = {os.path.join("skills", r["skill"], f"{k}.html") for r in rows for k, *_ in KINDS if r[k] == "internal"}
    if os.path.exists(dest): shutil.rmtree(dest)
    kept = dropped = 0
    for d, _, files in os.walk(SITE):
        for fn in files:
            if fn == ".DS_Store": continue
            rel = os.path.relpath(os.path.join(d, fn), SITE)
            if rel in internal: dropped += 1; continue
            os.makedirs(os.path.join(dest, os.path.dirname(rel)), exist_ok=True)
            shutil.copy2(os.path.join(d, fn), os.path.join(dest, rel)); kept += 1
    print(f"staged {kept} file(s) to {dest}; left out {dropped} internal page(s)")


# --------------------------------------------------------------------------- main
def main(argv):
    if argv[:1] == ["--stage"]:
        stage(argv[1] if len(argv) > 1 else os.path.join(ROOT, "_site")); return
    if argv[:1] == ["--sync"]:
        if len(argv) < 2: sys.exit("usage: build.py --sync PATH [REF]")
        sync(argv[1], argv[2] if len(argv) > 2 else "mosofin/main"); return
    rows = sorted(read_tracker(), key=sort_key)
    bad = problems(rows)
    if bad:
        print("\n".join("  FAIL  " + b for b in bad)); print(f"\n{len(bad)} problem(s)"); sys.exit(1)
    outs = outputs(rows)
    seo_bad = seo_problems(outs) + voice_problems(outs)
    if seo_bad:
        print("\n".join("  FAIL  " + b for b in seo_bad)); print(f"\n{len(seo_bad)} search problem(s)"); sys.exit(1)
    if argv[:1] == ["--check"]:
        stale = [os.path.relpath(p, ROOT) for p, h in outs.items() if not os.path.exists(p) or open(p).read() != h]
        orphans = [os.path.relpath(os.path.join(SITE, "skills", s, "index.html"), ROOT)
                   for s in (os.listdir(os.path.join(SITE, "skills")) if os.path.isdir(os.path.join(SITE, "skills")) else [])
                   if os.path.join(SITE, "skills", s, "index.html") not in outs
                   and os.path.exists(os.path.join(SITE, "skills", s, "index.html"))]
        for p in stale: print(f"  STALE {p} — run python3 build.py")
        for p in orphans: print(f"  ORPHAN {p} — no tracked explainers for this skill")
        if stale or orphans: sys.exit(1)
        print(f"ok: {len(rows)} skills tracked, {len(outs)} generated pages up to date"); return
    for p, h in outs.items():
        os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, "w").write(h)
    print(f"built {len(outs)} page(s) from {len(rows)} tracked skills")

if __name__ == "__main__":
    main(sys.argv[1:])
